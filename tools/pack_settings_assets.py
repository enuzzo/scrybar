#!/usr/bin/env python3
"""Refresh the settings representations and their Arduino assembly dependency."""
import argparse
import gzip
import hashlib
from pathlib import Path

assets = Path(__file__).resolve().parents[1] / "src/settings_assets"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()

lines = ["/* Generated by tools/pack_settings_assets.py */", ".section .rodata"]
for kind in ("css", "js"):
    plain = assets / f"settings.{kind}"
    packed = plain.with_suffix(plain.suffix + ".gz")
    data = plain.read_bytes()
    if args.check:
        if gzip.decompress(packed.read_bytes()) != data:
            raise SystemExit(f"{packed.name} is stale. Run tools/pack_settings_assets.py.")
    else:
        packed.write_bytes(gzip.compress(data, compresslevel=9, mtime=0))

    for suffix, source in (("", plain), ("_gzip", packed)):
        symbol = f"settings_{kind}{suffix}"
        # Arduino's dependency scanner cannot see .incbin. Changing the assembly
        # source ensures an incremental compile picks up edits to either asset.
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        lines.extend([
            f"/* {source.name} SHA-256 {digest} */", ".balign 4",
            f".global {symbol}_start, {symbol}_end", f"{symbol}_start:",
            f'.incbin "src/settings_assets/{source.name}"', f"{symbol}_end:",
        ])

assembly = assets / "assets.S"
expected = "\n".join(lines) + "\n"
if not assembly.exists() or assembly.read_text() != expected:
    if args.check:
        raise SystemExit("assets.S is stale. Run tools/pack_settings_assets.py.")
    assembly.write_text(expected)
